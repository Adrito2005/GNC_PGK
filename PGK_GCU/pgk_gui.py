    # ---------------- BRIDGE ----------------
    def _gather_inputs(self):
        return {
            "launch_long":   self.launch_long.get().strip()  or "0",
            "launch_lat":    self.launch_lat.get().strip()   or "0",
            "launch_height": self.launch_height.get().strip()or "0",
            "impact_long":   self.impact_long.get().strip()  or "0",
            "impact_lat":    self.impact_lat.get().strip()   or "0",
            "impact_height": self.impact_height.get().strip()or "0",
            "detonation_type": self.detonation_combo.get(),
        }

    def _call_cpp(self, command):
        data = self._gather_inputs()
        for k in ("launch_long","launch_lat","launch_height",
                  "impact_long","impact_lat","impact_height"):
            try:
                float(data[k])
            except ValueError:
                self._show_error(f"Invalid {k}")
                return None
        try:
            return self.bridge.run(data, command)
        except Exception as e:
            self._show_error(str(e))
            return None

    def _show_error(self, msg):
        self.time_to_impact_var.set("INPUT ERR")
        self.time_at_detonation_var.set("INPUT ERR")
        self.progress_text.set("0%")
        self.mono_code_var.set("INVALID COORDINATES")
        self.status_var.set(f"STATUS: ERROR — {msg}")
        self.progress_bar['value'] = 0

    def _apply_output(self, out):
        if not out: return
        self.time_to_impact_var.set(f"{out.get('time_to_impact','0')} s")
        self.time_at_detonation_var.set(f"{out.get('time_to_detonation','0')} s")
        self.progress_bar['value'] = float(out.get('progress', 0))
        self.progress_text.set(f"{out.get('progress','0')}%")
        self.mono_code_var.set(out.get('mono_code', ''))
        self.status_var.set(f"STATUS: {out.get('status','OK')}")

    # ---------------- AUTO-SAVE ----------------
    def _autosave(self, last_command: str = "CALCULATE"):
        """Silently write current mission state to the active JSON file."""
        try:
            MissionStore.ensure_missions_dir()
            payload = MissionStore.to_dict(self, last_command=last_command)
            payload["mission_name"] = os.path.splitext(
                os.path.basename(self._current_mission_path))[0]
            with open(self._current_mission_path, "w", encoding="utf-8") as f:
                json.dump(payload, f, indent=2)
            ts = datetime.now().strftime("%H:%M:%S")
            self.autosave_var.set(
                f"AUTOSAVE ✓ {os.path.basename(self._current_mission_path)} @ {ts}"
            )
        except Exception as e:
            self.autosave_var.set(f"AUTOSAVE FAILED: {e}")

    # ---------------- BUTTON HANDLERS ----------------
    def calculate_ballistics(self):
        out = self._call_cpp("CALCULATE")
        self._apply_output(out)
        if out:                              # only autosave on success
            self._autosave(last_command="CALCULATE")

    def on_detonation_select(self, event):
        sel = self.detonation_combo.get()
        self.detonation_timing_label.config(text={
            "Time": "T+0.00s (Delay)",
            "Proximity": "T+Proximity",
            "Impact": "T+Impact",
            "IED": "Signal Based",
            "Manual Override": "Awaiting Input",
        }.get(sel, "T+Impact"))
        self.calculate_ballistics()

    def run_mono_cast(self):
        out = self._call_cpp("MONO_CAST")
        self._apply_output(out)
        if out:
            self._autosave(last_command="MONO_CAST")

    def run_mass(self):
        out = self._call_cpp("MASS_CAST")
        self._apply_output(out)
        if out:
            self._autosave(last_command="MASS_CAST")

    def run_instant(self):
        out = self._call_cpp("INSTANT_DETONATION")
        self._apply_output(out)
        if out:
            self._autosave(last_command="INSTANT_DETONATION")

    # ================ SAVE AS / LOAD ================
    def save_mission_as(self):
        """Choose a new filename; from then on auto-save writes to it."""
        MissionStore.ensure_missions_dir()
        initial = os.path.join(
            MISSIONS_DIR,
            f"mission_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
        )
        path = filedialog.asksaveasfilename(
            title="Save Mission As",
            initialdir=MISSIONS_DIR,
            initialfile=os.path.basename(initial),
            defaultextension=".json",
            filetypes=[("JSON Mission", "*.json"), ("All Files", "*.*")]
        )
        if not path:
            return
        self._current_mission_path = path
        self._autosave(last_command="SAVE_AS")
        self.status_var.set(f"STATUS: SWITCHED TO ← {os.path.basename(path)}")

    def load_mission(self):
        """Load JSON; the loaded file becomes the new auto-save target."""
        MissionStore.ensure_missions_dir()
        path = filedialog.askopenfilename(
            title="Load Mission",
            initialdir=MISSIONS_DIR,
            filetypes=[("JSON Mission", "*.json"), ("All Files", "*.*")]
        )
        if not path:
            return

        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)

            if not isinstance(data, dict) or "inputs" not in data:
                raise ValueError("File is not a valid PGK mission (missing 'inputs').")

            version = data.get("version", "?")
            MissionStore.from_dict(self, data)
            self._current_mission_path = path   # switch autosave target

            # Recompute C++ outputs from loaded inputs (and autosave refresh)
            out = self._call_cpp("CALCULATE")
            self._apply_output(out)
            if out:
                self._autosave(last_command="LOAD")

            self.status_var.set(
                f"STATUS: LOADED ← {os.path.basename(path)}  (schema v{version})"
            )
        except json.JSONDecodeError as e:
            messagebox.showerror("Load Failed", f"Invalid JSON:\n{e}")
            self.status_var.set("STATUS: LOAD FAILED (bad JSON)")
        except Exception as e:
            messagebox.showerror("Load Failed", f"Could not load mission:\n{e}")
            self.status_var.set("STATUS: LOAD FAILED")



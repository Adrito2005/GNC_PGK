# =====================================================================
#  C++ BRIDGE
# =====================================================================
class CppBridge:
    def __init__(self):
        self._compiled = False

    def ensure_compiled(self):
        if self._compiled and os.path.exists(CPP_EXE):
            return
        compiler = None
        for c in ("g++", "clang++", "c++"):
            if shutil.which(c):
                compiler = c
                break
        if not compiler:
            raise RuntimeError("No C++ compiler found. Install g++ / MinGW.")
        if not os.path.exists(CPP_SRC):
            raise RuntimeError(f"Missing source: {CPP_SRC}")
        r = subprocess.run(
            [compiler, "-O2", "-std=c++17", CPP_SRC, "-o", CPP_EXE],
            capture_output=True, text=True
        )
        if r.returncode != 0:
            raise RuntimeError(f"C++ compile failed:\n{r.stderr}")
        self._compiled = True

    def write_state_header(self, data: dict, command: str):
        def fmt(v):
            try:
                return str(float(v))
            except (ValueError, TypeError):
                return "0.0"
        lines = [
            "// Auto-generated by pgk_gui.py — DO NOT EDIT",
            "#ifndef MISSION_STATE_H",
            "#define MISSION_STATE_H",
            "namespace MissionState {",
            f"    static const double launch_long   = {fmt(data.get('launch_long', 0))};",
            f"    static const double launch_lat    = {fmt(data.get('launch_lat', 0))};",
            f"    static const double launch_height = {fmt(data.get('launch_height', 0))};",
            f"    static const double impact_long   = {fmt(data.get('impact_long', 0))};",
            f"    static const double impact_lat    = {fmt(data.get('impact_lat', 0))};",
            f"    static const double impact_height = {fmt(data.get('impact_height', 0))};",
            f"    static const char*  detonation    = \"{data.get('detonation_type','Impact')}\";",
            f"    static const char*  command       = \"{command}\";",
            "}",
            "#endif",
            ""
        ]
        try:
            with open(STATE_H, "w", encoding="utf-8") as f:
                f.write("\n".join(lines))
        except OSError:
            pass

    def run(self, data: dict, command: str = "CALCULATE") -> dict:
        self.ensure_compiled()
        self.write_state_header(data, command)
        payload_lines = [f"{k}={v}" for k, v in data.items()]
        payload_lines.append(f"command={command}")
        payload = "\n".join(payload_lines) + "\n"
        r = subprocess.run([CPP_EXE], input=payload,
                           capture_output=True, text=True, timeout=10)
        if r.returncode != 0:
            raise RuntimeError(f"C++ runtime error: {r.stderr}")
        out = {}
        for ln in r.stdout.strip().splitlines():
            if "=" in ln:
                k, v = ln.split("=", 1)
                out[k.strip()] = v.strip()
        return out



class MissionStore:
    SCHEMA_VERSION = "1.0"

    @staticmethod
    def ensure_missions_dir():
        os.makedirs(MISSIONS_DIR, exist_ok=True)

    @staticmethod
    def to_dict(app, last_command: str = "CALCULATE") -> dict:
        return {
            "version": MissionStore.SCHEMA_VERSION,
            "saved_at": datetime.now().isoformat(timespec="seconds"),
            "last_command": last_command,
            "mission_name": os.path.splitext(os.path.basename(
                getattr(app, "_current_mission_path", "current_mission")))[0],
            "inputs": {
                "launch_long":   app.launch_long.get().strip(),
                "launch_lat":    app.launch_lat.get().strip(),
                "launch_height": app.launch_height.get().strip(),
                "impact_long":   app.impact_long.get().strip(),
                "impact_lat":    app.impact_lat.get().strip(),
                "impact_height": app.impact_height.get().strip(),
            },
            "detonation": {
                "type": app.detonation_combo.get(),
                "timing_label": app.detonation_timing_label.cget("text"),
            },
            "last_outputs": {
                "time_to_impact":     app.time_to_impact_var.get(),
                "time_to_detonation": app.time_at_detonation_var.get(),
                "progress":           int(app.progress_bar["value"]),
                "mono_code":          app.mono_code_var.get(),
            },
        }

    @staticmethod
    def from_dict(app, data: dict):
        inputs = data.get("inputs", {})
        app.launch_long.set(str(inputs.get("launch_long", "")))
        app.launch_lat.set(str(inputs.get("launch_lat", "")))
        app.launch_height.set(str(inputs.get("launch_height", "")))
        app.impact_long.set(str(inputs.get("impact_long", "")))
        app.impact_lat.set(str(inputs.get("impact_lat", "")))
        app.impact_height.set(str(inputs.get("impact_height", "")))

        det = data.get("detonation", {})
        det_type = det.get("type", "Impact")
        if det_type in app.detonation_options:
            app.detonation_combo.set(det_type)
        timing = det.get("timing_label")
        if timing:
            app.detonation_timing_label.config(text=timing)

        outputs = data.get("last_outputs", {})
        if outputs:
            app.time_to_impact_var.set(str(outputs.get("time_to_impact", "---")))
            app.time_at_detonation_var.set(str(outputs.get("time_to_detonation", "---")))
            try:
                app.progress_bar["value"] = float(outputs.get("progress", 0))
                app.progress_text.set(f"{int(outputs.get('progress', 0))}%")
            except (ValueError, TypeError):
                pass
            app.mono_code_var.set(str(outputs.get("mono_code", "")))


